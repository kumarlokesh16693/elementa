#!/usr/bin/env python3
"""Generate src/lib/periodic/origins.ts from the digitized chart data."""
import json

SRC = "/tmp/origins/origins_digitized.json"
OUT = "/home/z/my-project/src/lib/periodic/origins.ts"

META = [
    ("bigbang", "Big Bang fusion", "BB", "#3ba3f5",
     "Primordial Big Bang nucleosynthesis in the universe's first ~20 minutes — "
     "produced all hydrogen, most helium and a trace of lithium.",
     "H · He"),
    ("massive", "Exploding massive stars", "MS", "#12c997",
     "Hydrostatic fusion during the lives of stars ≳8 M☉ plus their core-collapse "
     "supernovae — the α elements O, Ne, Mg, Si, S, Ar, Ca and part of the iron peak.",
     "O · Si · Ca"),
    ("lowmass", "Dying low-mass stars", "AGB", "#f2d24b",
     "Helium-shell flashes and the slow neutron-capture (s-) process during the "
     "asymptotic-giant-branch phase of stars ≲8 M☉ — C, N and much of the light s-process nuclei.",
     "C · N · Sr"),
    ("whitedwarf", "Exploding white dwarfs", "Ia", "#6fd0fb",
     "Type Ia supernovae — thermonuclear disruption of a white dwarf reaching the "
     "Chandrasekhar mass — a dominant source of the iron peak.",
     "Fe · Ni · Zn"),
    ("neutronstar", "Merging neutron stars", "NS", "#f97316",
     "Rapid neutron capture (r-process) in neutron-star mergers, confirmed by the "
     "GW170817 kilonova — Au, Pt, the rare earths, Th and U.",
     "Au · Pt · Eu"),
    ("cosmicray", "Cosmic-ray fission", "CR", "#e879d8",
     "Cosmic-ray spallation — high-energy particles fragmenting C and O nuclei in the "
     "interstellar medium — the only major source of Li, Be and B.",
     "Li · Be · B"),
    ("synthetic", "Synthetic (man-made)", "SYN", "#8b98ab",
     "No natural solar-system abundance: created in nuclear reactors and particle "
     "accelerators, with at most ephemeral traces from natural decay chains.",
     "Tc · Pm · Z ≥ 93"),
]

NOTES = {
    43: "Technetium has no stable isotopes. The chart leaves it grey: trace amounts "
        "exist in uranium ores from spontaneous fission, and Tc lines are observed "
        "in AGB stars — but it contributes no solar-system abundance.",
    61: "Promethium has no stable or long-lived isotopes; all primordial Pm has decayed. "
        "The chart leaves it grey.",
    93: "Neptunium: no primordial abundance — only trace Np-237 from neutron capture in "
        "uranium ores.",
    94: "Plutonium: no primordial abundance — only trace Pu-244 and fission-born Pu-239 "
        "in nature.",
}

data = json.load(open(SRC))

def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")

def fmt_pair(p):
    return f"['{p[0]}', {p[1]}]"

lines = []
for z in range(1, 119):
    if str(z) in data:
        pairs = ", ".join(fmt_pair(p) for p in data[str(z)])
        lines.append(f"  {z}: [{pairs}],")

data_block = "\n".join(lines)

meta_block = ",\n".join(
    f"  {{ key: '{k}', label: '{esc(label)}', short: '{short}', color: '{color}', example: '{esc(ex)}', desc: '{esc(d)}' }}"
    for k, label, short, color, d, ex in META
)

notes_block = ",\n".join(
    f"  {z}: '{esc(t.replace(chr(10), ' '))}'" for z, t in NOTES.items()
)

ts = f"""// AUTO-GENERATED by scripts/gen_origins_ts.py — do not edit by hand.
//
// Source: pixel-digitized from J. A. Johnson (OSU / SDSS), "The Origin of the
// Solar System Elements", 2019 revision (blog.sdss.org/2017/01/09), CC BY-SA.
// Digitizer: scripts/digitize_origins.py — each element tile in the chart is
// flat-filled with one color per nucleosynthesis channel; the area fraction of
// each color gives that channel's share. Values are therefore approximate
// (±~3%) and rounded to integers summing to 100.
// Coverage: elements with a natural solar-system abundance (all Z ≤ 92 except
// 43 Tc and 61 Pm, which the chart leaves grey). Heavier elements are synthetic.

import type {{ ElementData }} from './types'

export type OriginKey =
  | 'bigbang'
  | 'massive'
  | 'lowmass'
  | 'whitedwarf'
  | 'neutronstar'
  | 'cosmicray'
  | 'synthetic'

export interface OriginMeta {{
  key: OriginKey
  /** legend label */
  label: string
  /** 2-3 letter tag shown inside tiles */
  short: string
  color: string
  /** flagship elements */
  example: string
  desc: string
}}

export const ORIGINS: OriginMeta[] = [
{meta_block},
]

export const ORIGIN_MAP: Record<OriginKey, OriginMeta> = Object.fromEntries(
  ORIGINS.map((o) => [o.key, o]),
) as Record<OriginKey, OriginMeta>

/**
 * Percentage contribution of each nucleosynthesis channel to the solar-system
 * abundance of an element (descending). Elements absent from the chart are
 * synthetic (or have no natural abundance) and map to [['synthetic', 100]].
 */
export const ORIGIN_DATA: Record<number, [OriginKey, number][]> = {{
{data_block}
}}

/** Elements the source chart deliberately leaves grey, with the reason. */
export const ORIGIN_NOTES: Record<number, string> = {{
{notes_block}
}}

export function originsFor(z: number): [OriginKey, number][] {{
  return ORIGIN_DATA[z] ?? [['synthetic', 100]]
}}

export function dominantOrigin(z: number): [OriginKey, number] {{
  const pairs = originsFor(z)
  return pairs[0]
}}

/** Share (0-100) of a given channel in element z's solar-system abundance. */
export function originPct(z: number, key: OriginKey): number {{
  return originsFor(z).find(([k]) => k === key)?.[1] ?? 0
}}

export function originSummary(z: number): string {{
  return originsFor(z)
    .map(([k, v]) => `~${{v}}% ${{ORIGIN_MAP[k].label.toLowerCase()}}`)
    .join(' · ')
}}

export const ORIGIN_FOOTNOTE =
  'Origin shares are digitized from J. A. Johnson (OSU/SDSS), "The Origin of the ' +
  'Solar System Elements" (2019 revision, CC BY-SA) — expert estimates encoded as ' +
  'color fractions, accurate to a few percent. The chart leaves Tc, Pm and Z > 92 ' +
  'grey: they have no natural solar-system abundance.'
"""

with open(OUT, "w") as f:
    f.write(ts)
print(f"wrote {OUT} ({len(ts)} bytes, {len(data)} elements)")
